#!/usr/bin/env python3
"""
MD Simulation: Fix Dissociated Ligands

Re-builds PfDHFR (201) and PfClpP (164) complexes with binding-site restraints
to prevent ligand dissociation during energy minimization and equilibration.

Strategy:
1. Place ligand in binding pocket using docking pose or binding site center
2. Add position restraints to ligand heavy atoms during EM
3. Gradually release restraints during NVT equilibration
4. Run 100 ps test to validate binding before full production

Usage:
    python scripts/md_fix_dissociated_ligands.py --complex 201_PfDHFR
    python scripts/md_fix_dissociated_ligands.py --complex 164_PfClpP
    python scripts/md_fix_dissociated_ligands.py --complex all
"""

